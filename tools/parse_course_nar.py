def nf(s):
    return unicodedata.normalize("NFKC", s).strip()


def blocks(paths):
    for p in paths:
        cur = None
        for line in open(p, encoding="utf-8"):
            line = line.rstrip("\n")
            if line.startswith("##### 記事"):
                if cur:
                    yield cur
                cur = [line]
            elif cur is not None:
                cur.append(line)
        if cur:
            yield cur


def parse_block(b):
    url = b[0].split(" ", 2)[2].strip()
    title = next((nf(re.sub(r"^##### 題名\s*", "", l)) for l in b if l.startswith("##### 題名")), "")
    m = re.match(r"^(.+?)競馬場(芝|ダート)?(\d{3,4})m 特徴", title)
    m2 = re.match(r"^(.+?)競馬場特徴と傾向", title)
    if m:
        venue, surf, dist = m.group(1), "芝" if m.group(2) == "芝" else "ダ", int(m.group(3))
    elif m2:
        venue, surf, dist = m2.group(1), "ダ", None
    else:
        return None
    t = "\n".join(b)
    d = {"venue": venue, "surface": surf, "dist": dist, "url": url, "waku": {}, "style": {}, "ninki": {}}
    for x in re.finditer(r"(\d)枠 の成績は（1着(\d+)回・2着(\d+)回・3着(\d+)回・着外(\d+)回）", t):
        a, b2, c, e = map(int, x.groups()[1:])
        d["waku"][x.group(1)] = [a + b2 + c + e, a, a + b2 + c]
    for k, name in (("勝　率", "win"), ("連対率", "top2"), ("複勝率", "top3")):
        x = re.search(r"^\| " + k + r" \| (\d+)% \| (\d+)% \| (\d+)% \| (\d+)%$", t, re.M)
        if x:
            for st, v in zip(STYLE, x.groups()):
                d["style"].setdefault(st, {})[name] = int(v)
    for x in re.finditer(r"(\d)番人気 の成績は（1着(\d+)回・2着(\d+)回・3着(\d+)回?・着外(\d+)回）[^\n]*?複勝率(\d+)パーセント", t):
        a, b2, c, e = map(int, x.groups()[1:5])
        rate = int(x.group(6)) / 100
        # 記事によって「着外」が出走数そのものになっている。書いてある複勝率に合う方を出走数にする
        n = min((a + b2 + c + e, e), key=lambda m: abs((a + b2 + c) / m - rate) if m else 9)
        d["ninki"][x.group(1)] = [n, a, a + b2 + c]
    if not (d["waku"] or d["style"] or d["ninki"]):
        if not (dist and COURSE_NOTES.get((venue, surf, dist))):
            return None
        d["stats"] = "場全体"        # 数字の無い距離。説明だけ持ち、数字は場全体を使う
    d["note"] = COURSE_NOTES.get((venue, surf, dist)) if dist else VENUE_NOTES.get(venue)
    return d


def main():
    out, paths = sys.argv[1], sys.argv[2:]
    courses, venues = [], {}
    for b in blocks(paths):
        d = parse_block(b)
        if not d:
            continue
        if d["dist"] is None:
            venues[d["venue"]] = d
        else:
            courses.append(d)
    for v, note in VENUE_NOTES.items():
        venues.setdefault(v, {"venue": v, "surface": "ダ", "dist": None, "waku": {}, "style": {}, "ninki": {}})
